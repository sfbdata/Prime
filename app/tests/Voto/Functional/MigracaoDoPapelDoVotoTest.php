<?php

declare(strict_types=1);

namespace App\Tests\Voto\Functional;

use Doctrine\DBAL\Connection;
use Doctrine\ORM\EntityManagerInterface;
use PHPUnit\Framework\Attributes\CoversNothing;
use PHPUnit\Framework\Attributes\TestDox;
use Symfony\Bundle\FrameworkBundle\Console\Application;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\Console\Tester\CommandTester;

/**
 * A migration `Version20261109160000` (spec bluejus-voto §7, M2) desce e sobe de verdade no banco de teste, dentro da
 * transação do DAMA (o banco volta como estava; o Postgres desfaz GRANT e ALTER DEFAULT PRIVILEGES na transação).
 *
 * Prova o que só o catálogo do Postgres mostra: o papel `voto_acesso` existe e não entra no banco (NOLOGIN), tem
 * USAGE no schema `voto`, recebe por privilégio padrão as tabelas e sequências FUTURAS do schema e não tem nada na
 * `voto.liberacao`, que é dado do BlueJus. Do schema `public` só lê a `recurso_estado` (o guarda de recurso do Master
 * a consulta no container do Voto). O down tira as permissões e deixa o papel (ele é do cluster inteiro), e o up roda
 * de novo com o papel já existente.
 *
 * Cada teste prepara o próprio estado ({@see PapelDoVotoNoBancoDeTeste}): o snapshot de teste não leva papel nem
 * privilégios.
 */
#[CoversNothing]
final class MigracaoDoPapelDoVotoTest extends KernelTestCase
{
    private const VERSAO = 'DoctrineMigrations\\Version20261109160000';
    private const PAPEL = 'voto_acesso';

    #[TestDox('down tira o USAGE, o privilégio padrão e a leitura de recurso_estado e deixa o papel; up devolve tudo, sem tocar na voto.liberacao')]
    public function testDownEUp(): void
    {
        self::bootKernel();
        PapelDoVotoNoBancoDeTeste::preparar($this->banco());
        self::assertSame(0, $this->executar('--down'));
        $banco = $this->banco();
        self::assertTrue($this->papelExiste($banco), 'o down não apaga o papel: ele é do cluster');
        self::assertFalse($this->temUsage($banco), 'o down tira o USAGE no schema voto');
        self::assertSame([], $this->privilegiosPadrao($banco), 'o down tira o privilégio padrão');
        self::assertSame([], $this->tabelasDoPublicCom($banco, 'SELECT, INSERT, UPDATE, DELETE, TRUNCATE'), 'o down tira a leitura de recurso_estado');

        // A migration executada fica congelada na fábrica de dependências: cada execução precisa de um kernel novo.
        $this->subir();
        $this->conferirEstadoDoUp($this->banco());
    }

    #[TestDox('o up roda duas vezes seguidas sem erro (papel e permissões já existentes) e deixa o mesmo estado')]
    public function testUpRodaDuasVezes(): void
    {
        self::bootKernel();
        $banco = $this->banco();
        PapelDoVotoNoBancoDeTeste::preparar($banco);
        self::assertTrue($this->papelExiste($banco), 'primeiro up, feito pela preparação');
        // Sem a linha da versão, o `execute --up` grava de novo em doctrine_migration_versions em vez de falhar na chave.
        $banco->executeStatement('DELETE FROM doctrine_migration_versions WHERE version = ?', [self::VERSAO]);

        $this->subir();
        $this->conferirEstadoDoUp($this->banco());
    }

    #[TestDox('tabela nova no schema voto nasce com leitura e escrita para voto_acesso; a voto.liberacao segue sem nada')]
    public function testTabelaFuturaRecebeOPrivilegio(): void
    {
        self::bootKernel();
        $banco = $this->banco();
        PapelDoVotoNoBancoDeTeste::preparar($banco);
        $banco->executeStatement('CREATE TABLE voto.teste_privilegio_padrao (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)');

        foreach (['SELECT', 'INSERT', 'UPDATE', 'DELETE'] as $privilegio) {
            self::assertTrue($this->temNaTabela($banco, 'voto.teste_privilegio_padrao', $privilegio), $privilegio . ' na tabela futura');
            self::assertFalse($this->temNaTabela($banco, 'voto.liberacao', $privilegio), $privilegio . ' na voto.liberacao');
        }
        self::assertFalse($this->temNaTabela($banco, 'voto.teste_privilegio_padrao', 'TRUNCATE'), 'TRUNCATE fica de fora');
        self::assertTrue((bool) $banco->fetchOne(
            "SELECT has_sequence_privilege(?, pg_get_serial_sequence('voto.teste_privilegio_padrao', 'id'), 'USAGE')",
            [self::PAPEL],
        ), 'USAGE na sequência da tabela futura');
    }

    private function conferirEstadoDoUp(Connection $banco): void
    {
        self::assertSame(
            ['rolcanlogin' => false, 'rolsuper' => false, 'rolcreaterole' => false, 'rolcreatedb' => false],
            $banco->fetchAssociative(
                'SELECT rolcanlogin, rolsuper, rolcreaterole, rolcreatedb FROM pg_roles WHERE rolname = ?',
                [self::PAPEL],
            ),
            'voto_acesso existe, é NOLOGIN e não tem atributo de administração',
        );
        self::assertTrue($this->temUsage($banco), 'USAGE no schema voto');
        self::assertFalse((bool) $banco->fetchOne("SELECT has_schema_privilege(?, 'voto', 'CREATE')", [self::PAPEL]), 'sem CREATE no schema voto');
        self::assertSame(['S' => 'rU', 'r' => 'arwd'], $this->privilegiosPadrao($banco), 'tabelas: arwd; sequências: rU');
        foreach (['SELECT', 'INSERT', 'UPDATE', 'DELETE'] as $privilegio) {
            self::assertFalse($this->temNaTabela($banco, 'voto.liberacao', $privilegio), $privilegio . ' na voto.liberacao (dado do BlueJus)');
        }
        self::assertSame(['recurso_estado'], $this->tabelasDoPublicCom($banco, 'SELECT'), 'do public, só lê a recurso_estado');
        self::assertSame([], $this->tabelasDoPublicCom($banco, 'INSERT, UPDATE, DELETE, TRUNCATE'), 'não escreve em nada do public');
        foreach (['public.user', 'public.tenant', 'public.user_tenant'] as $tabela) {
            self::assertFalse($this->temNaTabela($banco, $tabela, 'SELECT'), 'nada em ' . $tabela);
        }
    }

    /**
     * Tabelas do schema `public` em que o papel tem ao menos um dos privilégios (lista separada por vírgula, como o
     * has_table_privilege aceita).
     *
     * @return list<string>
     */
    private function tabelasDoPublicCom(Connection $banco, string $privilegios): array
    {
        return $banco->fetchFirstColumn(
            "SELECT tablename FROM pg_tables
              WHERE schemaname = 'public' AND has_table_privilege(?, format('%I.%I', schemaname, tablename), ?)
              ORDER BY tablename",
            [self::PAPEL, $privilegios],
        );
    }

    private function subir(): void
    {
        self::ensureKernelShutdown();
        self::bootKernel();
        self::assertSame(0, $this->executar('--up'));
    }

    private function executar(string $sentido): int
    {
        $application = new Application(self::$kernel);
        $tester = new CommandTester($application->find('doctrine:migrations:execute'));

        return $tester->execute(['versions' => [self::VERSAO], $sentido => true], ['interactive' => false]);
    }

    private function banco(): Connection
    {
        return static::getContainer()->get(EntityManagerInterface::class)->getConnection();
    }

    private function papelExiste(Connection $banco): bool
    {
        return (int) $banco->fetchOne('SELECT COUNT(*) FROM pg_roles WHERE rolname = ?', [self::PAPEL]) === 1;
    }

    private function temUsage(Connection $banco): bool
    {
        return (bool) $banco->fetchOne("SELECT has_schema_privilege(?, 'voto', 'USAGE')", [self::PAPEL]);
    }

    private function temNaTabela(Connection $banco, string $tabela, string $privilegio): bool
    {
        return (bool) $banco->fetchOne('SELECT has_table_privilege(?, ?, ?)', [self::PAPEL, $tabela, $privilegio]);
    }

    /**
     * Privilégio padrão do papel no schema voto, por tipo de objeto (r = tabela, S = sequência), no formato do aclitem
     * (a = INSERT, r = SELECT, w = UPDATE, d = DELETE, U = USAGE).
     *
     * @return array<string, string>
     */
    private function privilegiosPadrao(Connection $banco): array
    {
        $linhas = $banco->fetchAllAssociative(
            "SELECT d.defaclobjtype AS tipo, a.privilege_type AS privilegio
               FROM pg_default_acl d
               JOIN pg_namespace n ON n.oid = d.defaclnamespace
               CROSS JOIN LATERAL aclexplode(d.defaclacl) a
              WHERE n.nspname = 'voto' AND a.grantee = (SELECT oid FROM pg_roles WHERE rolname = ?)",
            [self::PAPEL],
        );
        $letras = ['INSERT' => 'a', 'SELECT' => 'r', 'UPDATE' => 'w', 'DELETE' => 'd', 'USAGE' => 'U'];
        $ordem = array_flip(array_values($letras));
        $porTipo = [];
        foreach ($linhas as $linha) {
            $porTipo[(string) $linha['tipo']][] = $letras[(string) $linha['privilegio']] ?? '?';
        }
        foreach ($porTipo as $tipo => $lista) {
            usort($lista, static fn (string $a, string $b): int => ($ordem[$a] ?? 99) <=> ($ordem[$b] ?? 99));
            $porTipo[$tipo] = implode('', $lista);
        }
        ksort($porTipo);

        return $porTipo;
    }
}
